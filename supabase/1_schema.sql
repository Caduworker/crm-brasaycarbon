-- El dueño cambia nombre, rol o activa/desactiva a alguien del equipo.
create or replace function public.admin_guardar_usuario(p_id uuid, p_nombre text, p_rol text, p_activo boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.es_admin() then raise exception 'Solo el dueño puede administrar usuarios'; end if;
  if p_id = auth.uid() and (p_rol <> 'admin' or not p_activo) then
    raise exception 'No puedes quitarte el acceso de dueño a ti mismo';
  end if;
  update public.perfiles set nombre = p_nombre, rol = p_rol, activo = p_activo where id = p_id;
end $$;

-- Envía a cocina los platos nuevos de un pedido. Devuelve el número de ticket.
create or replace function public.enviar_a_cocina(p_pedido bigint)
returns int language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_num int;
begin
  if not public.tiene_rol(array['admin','cajero','mozo']) then
    raise exception 'No tienes permiso para enviar pedidos a cocina';
  end if;
  if not exists (select 1 from public.pedido_items where pedido_id = p_pedido and comanda_id is null) then
    raise exception 'No hay platos nuevos para enviar a cocina';
  end if;
  insert into public.comandas (pedido_id) values (p_pedido) returning id, numero into v_id, v_num;
  update public.pedido_items set comanda_id = v_id where pedido_id = p_pedido and comanda_id is null;
  return v_num;
end $$;

-- Cobra un pedido: registra el pago, libera la mesa y descuenta el inventario según las recetas.
create or replace function public.cobrar_pedido(p_pedido bigint, p_metodo text, p_personas int default 1)
returns void language plpgsql security definer set search_path = public as $$
declare v_total numeric; v_mesa int; v_caja bigint;
begin
  if not public.tiene_rol(array['admin','cajero']) then raise exception 'Solo caja o el dueño pueden cobrar'; end if;
  select mesa_id into v_mesa from public.pedidos where id = p_pedido and estado = 'abierto' for update;
  if not found then raise exception 'Este pedido ya fue cobrado o no existe'; end if;
  select coalesce(sum(precio * cantidad), 0) into v_total from public.pedido_items where pedido_id = p_pedido;
  if v_total <= 0 then raise exception 'El pedido está vacío'; end if;
  select id into v_caja from public.cajas where estado = 'abierta' order by id desc limit 1;
  if v_caja is null then raise exception 'La caja está cerrada. Ábrela en la pantalla Caja antes de cobrar'; end if;

  if exists (select 1 from public.pedido_items where pedido_id = p_pedido and comanda_id is null) then
    perform public.enviar_a_cocina(p_pedido);
  end if;

  insert into public.pagos (pedido_id, caja_id, monto, metodo, personas)
  values (p_pedido, v_caja, v_total, p_metodo, greatest(p_personas, 1));
  update public.pedidos set estado = 'pagado', total = v_total, pagado_en = now() where id = p_pedido;

  if v_mesa is not null then
    update public.mesas set estado = 'libre', mozo = null, abierta_desde = null, unida_a = null
     where id = v_mesa or unida_a = v_mesa;
  end if;

  update public.insumos i set stock = greatest(0, i.stock - s.q)
    from (select ri.insumo_id, sum(ri.cantidad * pi.cantidad) as q
            from public.pedido_items pi
            join public.receta_items ri on ri.producto_id = pi.producto_id
           where pi.pedido_id = p_pedido group by ri.insumo_id) s
   where i.id = s.insumo_id;
end $$;

create or replace function public.anular_pedido(p_pedido bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_mesa int;
begin
  if not public.tiene_rol(array['admin','cajero']) then raise exception 'Solo caja o el dueño pueden anular pedidos'; end if;
  select mesa_id into v_mesa from public.pedidos where id = p_pedido and estado = 'abierto' for update;
  if not found then raise exception 'Este pedido ya no está abierto'; end if;
  update public.pedidos set estado = 'anulado' where id = p_pedido;
  update public.comandas set estado = 'entregado', actualizado = now() where pedido_id = p_pedido;
  if v_mesa is not null then
    update public.mesas set estado = 'libre', mozo = null, abierta_desde = null, unida_a = null
     where id = v_mesa or unida_a = v_mesa;
  end if;
end $$;

-- Junta varias mesas en una sola cuenta (la mesa principal se queda con todos los platos).
create or replace function public.unir_mesas(p_principal int, p_otras int[])
returns void language plpgsql security definer set search_path = public as $$
declare v_main bigint; v_otro bigint; m int; v_cobrar boolean := false;
begin
  if not public.tiene_rol(array['admin','cajero','mozo']) then raise exception 'No tienes permiso para unir mesas'; end if;
  if p_principal = any(p_otras) then raise exception 'Elige mesas distintas'; end if;
  select id into v_main from public.pedidos where mesa_id = p_principal and estado = 'abierto' order by id limit 1;
  if v_main is null then raise exception 'La mesa % no tiene pedido abierto', p_principal; end if;
  if (select estado from public.mesas where id = p_principal) = 'cobrar' then v_cobrar := true; end if;
  foreach m in array p_otras loop
    select id into v_otro from public.pedidos where mesa_id = m and estado = 'abierto' order by id limit 1;
    if v_otro is null then raise exception 'La mesa % no tiene pedido abierto', m; end if;
    update public.pedido_items set pedido_id = v_main where pedido_id = v_otro;
    update public.comandas set pedido_id = v_main where pedido_id = v_otro;
    delete from public.pedidos where id = v_otro;
    if (select estado from public.mesas where id = m) = 'cobrar' then v_cobrar := true; end if;
    update public.mesas set unida_a = p_principal where unida_a = m;
    update public.mesas set estado = 'unida', unida_a = p_principal, mozo = null where id = m;
  end loop;
  update public.mesas set estado = case when v_cobrar then 'cobrar' else 'ocupada' end where id = p_principal;
end $$;

create or replace function public.separar_mesas(p_principal int)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.tiene_rol(array['admin','cajero','mozo']) then raise exception 'No tienes permiso para separar mesas'; end if;
  update public.mesas set estado = 'libre', unida_a = null, mozo = null, abierta_desde = null where unida_a = p_principal;
end $$;

create or replace function public.registrar_merma(p_insumo bigint, p_cantidad numeric, p_motivo text, p_nota text default null)
returns void language plpgsql security definer set search_path = public as $$
declare v public.insumos%rowtype;
begin
  if not public.tiene_rol(array['admin','cocina']) then raise exception 'No tienes permiso para registrar mermas'; end if;
  select * into v from public.insumos where id = p_insumo for update;
  if not found then raise exception 'Ese producto no existe en el inventario'; end if;
  insert into public.mermas (insumo_id, nombre, unidad, cantidad, motivo, nota, costo)
  values (v.id, v.nombre, v.unidad, p_cantidad, p_motivo, p_nota, round(p_cantidad * v.costo, 2));
  update public.insumos set stock = greatest(0, stock - p_cantidad) where id = p_insumo;
end $$;

create or replace function public.cerrar_caja(p_caja bigint, p_contado numeric)
returns void language plpgsql security definer set search_path = public as $$
declare v_fondo numeric; v_ef numeric; v_gas numeric; v_esp numeric;
begin
  if not public.tiene_rol(array['admin','cajero']) then raise exception 'Solo caja o el dueño pueden cerrar la caja'; end if;
  select fondo into v_fondo from public.cajas where id = p_caja and estado = 'abierta' for update;
  if not found then raise exception 'Esta caja ya está cerrada'; end if;
  select coalesce(sum(monto), 0) into v_ef  from public.pagos  where caja_id = p_caja and metodo = 'efectivo';
  select coalesce(sum(monto), 0) into v_gas from public.gastos where caja_id = p_caja;
  v_esp := v_fondo + v_ef - v_gas;
  update public.cajas set estado = 'cerrada', cerrada_en = now(), cerrada_por = auth.uid(),
         contado = p_contado, esperado = v_esp, diferencia = p_contado - v_esp
   where id = p_caja;
end $$;

