-- ---------------------------------------------------------------------
-- 7. CARPETA DE FOTOS DE LOS PLATOS (se crea sola)
--    Nombre: productos · Pública (para que las fotos se vean en el menú)
-- ---------------------------------------------------------------------
do $$
begin
  insert into storage.buckets (id, name, public) values ('productos', 'productos', true)
  on conflict (id) do update set public = true;

  drop policy if exists "fotos_ver" on storage.objects;
  create policy "fotos_ver" on storage.objects for select using (bucket_id = 'productos');
  drop policy if exists "fotos_subir" on storage.objects;
  create policy "fotos_subir" on storage.objects for insert to authenticated
    with check (bucket_id = 'productos' and public.es_admin());
  drop policy if exists "fotos_cambiar" on storage.objects;
  create policy "fotos_cambiar" on storage.objects for update to authenticated
    using (bucket_id = 'productos' and public.es_admin());
  drop policy if exists "fotos_borrar" on storage.objects;
  create policy "fotos_borrar" on storage.objects for delete to authenticated
    using (bucket_id = 'productos' and public.es_admin());
exception when others then
  raise notice 'No se pudo crear la carpeta de fotos automáticamente. Créala a mano: Storage > New bucket > nombre productos > Public.';
end $$;
