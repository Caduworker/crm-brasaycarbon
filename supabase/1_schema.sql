-- Una fila por cada persona que entra al sistema (se crea sola con cada usuario).
create table if not exists public.perfiles (
  id      uuid primary key references auth.users(id) on delete cascade,
  nombre  text not null default '',
  rol     text not null default 'mozo' check (rol in ('admin','cajero','cocina','mozo')),
  activo  boolean not null default false,
  creado  timestamptz not null default now()
);

create table if not exists public.categorias (
  id     bigint generated by default as identity primary key,
  clave  text unique not null,
  nombre text not null,
  icono  text not null default 'plate',
  orden  int  not null default 0
);

create table if not exists public.productos (
  id           uuid primary key default gen_random_uuid(),
  categoria_id bigint references public.categorias(id) on delete restrict,
  nombre       text not null,
  detalle      text not null default '',
  precio       numeric(10,2) not null check (precio >= 0),
  imagen_url   text,
  activo       boolean not null default true,
  orden        int not null default 0,
  creado       timestamptz not null default now()
);

create table if not exists public.mesas (
  id            int primary key,
  zona          text not null check (zona in ('Salón','Terraza')),
  sillas        int  not null default 4,
  estado        text not null default 'libre' check (estado in ('libre','ocupada','cobrar','unida')),
  mozo          text,
  abierta_desde timestamptz,
  unida_a       int references public.mesas(id) on delete set null
);

create table if not exists public.pedidos (
  id         bigint generated by default as identity primary key,
  tipo       text not null check (tipo in ('mesa','mostrador','llevar','delivery')),
  mesa_id    int references public.mesas(id) on delete set null,
  cliente    text,
  telefono   text,
  direccion  text,
  estado     text not null default 'abierto' check (estado in ('abierto','pagado','anulado')),
  total      numeric(10,2) not null default 0,
  creado     timestamptz not null default now(),
  pagado_en  timestamptz,
  creado_por uuid default auth.uid()
);

create sequence if not exists public.comanda_numero_seq start 1;

-- Cada vez que se "envía a cocina" se crea una comanda (el ticket de cocina).
create table if not exists public.comandas (
  id          bigint generated by default as identity primary key,
  numero      int not null default nextval('public.comanda_numero_seq'),
  pedido_id   bigint not null references public.pedidos(id) on delete cascade,
  estado      text not null default 'recibido' check (estado in ('recibido','prep','listo','camino','entregado')),
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now()
);

create table if not exists public.pedido_items (
  id          bigint generated by default as identity primary key,
  pedido_id   bigint not null references public.pedidos(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete set null,
  nombre      text not null,
  precio      numeric(10,2) not null,
  cantidad    int not null check (cantidad > 0),
  comanda_id  bigint references public.comandas(id) on delete set null,
  creado      timestamptz not null default now()
);

create table if not exists public.cajas (
  id          bigint generated by default as identity primary key,
  estado      text not null default 'abierta' check (estado in ('abierta','cerrada')),
  fondo       numeric(10,2) not null default 0,
  abierta_en  timestamptz not null default now(),
  abierta_por uuid default auth.uid(),
  cerrada_en  timestamptz,
  cerrada_por uuid,
  contado     numeric(10,2),
  esperado    numeric(10,2),
  diferencia  numeric(10,2)
);
create unique index if not exists una_sola_caja_abierta on public.cajas (estado) where estado = 'abierta';

create table if not exists public.pagos (
  id         bigint generated by default as identity primary key,
  pedido_id  bigint not null references public.pedidos(id) on delete cascade,
  caja_id    bigint references public.cajas(id) on delete set null,
  monto      numeric(10,2) not null,
  metodo     text not null check (metodo in ('efectivo','qr','tarjeta')),
  personas   int not null default 1,
  creado     timestamptz not null default now(),
  usuario_id uuid default auth.uid()
);

create table if not exists public.gastos (
  id       bigint generated by default as identity primary key,
  caja_id  bigint not null references public.cajas(id) on delete cascade,
  concepto text not null,
  monto    numeric(10,2) not null check (monto >= 0),
  creado   timestamptz not null default now()
);

create table if not exists public.insumos (
  id        bigint generated by default as identity primary key,
  nombre    text not null,
  categoria text not null default 'General',
  unidad    text not null default 'kg',
  stock     numeric(12,3) not null default 0,
  minimo    numeric(12,3) not null default 0,
  costo     numeric(10,2) not null default 0
);

-- Receta = lista de ingredientes de un plato (cantidad por 1 porción).
create table if not exists public.receta_items (
  producto_id uuid   not null references public.productos(id) on delete cascade,
  insumo_id   bigint not null references public.insumos(id) on delete cascade,
  cantidad    numeric(12,3) not null check (cantidad >= 0),
  primary key (producto_id, insumo_id)
);

create table if not exists public.mermas (
  id         bigint generated by default as identity primary key,
  insumo_id  bigint references public.insumos(id) on delete set null,
  nombre     text not null,
  unidad     text not null,
  cantidad   numeric(12,3) not null check (cantidad > 0),
  motivo     text not null,
  nota       text,
  costo      numeric(10,2) not null default 0,
  creado     timestamptz not null default now(),
  usuario_id uuid default auth.uid()
);

create index if not exists idx_items_pedido   on public.pedido_items (pedido_id);
create index if not exists idx_pedidos_estado on public.pedidos (estado);
create index if not exists idx_pagos_creado   on public.pagos (creado);
create index if not exists idx_mermas_creado  on public.mermas (creado);

